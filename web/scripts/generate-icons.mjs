#!/usr/bin/env node
// Generates src/app/design-system/icon/icons.generated.ts from the icon set of the identity
// guide (design/icons/*.svg, DESIGN.md § Iconography). Each icon becomes a list of plain SVG
// shapes (tag + attributes), so the icon component renders them without innerHTML.
//
//   node scripts/generate-icons.mjs          write the file
//   node scripts/generate-icons.mjs --check  fail if the file is out of date
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const ICONS_DIR = fileURLToPath(new URL('../../design/icons/', import.meta.url));
export const OUTPUT = fileURLToPath(
  new URL('../src/app/design-system/icon/icons.generated.ts', import.meta.url),
);

const SHAPES = new Set(['path', 'circle', 'rect', 'line', 'polyline', 'polygon', 'ellipse']);
const ATTRIBUTES = new Set([
  'd', 'cx', 'cy', 'r', 'rx', 'ry', 'x', 'y', 'x1', 'x2', 'y1', 'y2', 'width', 'height', 'points',
]);

function parseIcon(name, svg) {
  const body = svg.replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg\b[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '');
  const shapes = [];
  for (const [, tag, rawAttributes] of body.matchAll(/<([a-z]+)\b([^>]*?)\/?>/g)) {
    if (!SHAPES.has(tag)) {
      throw new Error(`${name}.svg: unsupported element <${tag}>`);
    }
    const attributes = {};
    for (const [, key, value] of rawAttributes.matchAll(/([a-z0-9-]+)="([^"]*)"/g)) {
      if (!ATTRIBUTES.has(key)) {
        throw new Error(`${name}.svg: unsupported attribute ${key} on <${tag}>`);
      }
      attributes[key] = value;
    }
    shapes.push({ tag, attributes });
  }
  if (shapes.length === 0) {
    throw new Error(`${name}.svg: no shapes`);
  }
  return shapes;
}

export async function generate() {
  const files = (await readdir(ICONS_DIR)).filter((f) => f.endsWith('.svg')).sort();
  const icons = {};
  for (const file of files) {
    const name = file.replace(/\.svg$/, '');
    icons[name] = parseIcon(name, await readFile(`${ICONS_DIR}${file}`, 'utf8'));
  }
  const entries = Object.entries(icons)
    .map(([name, shapes]) => {
      const lines = shapes.map(
        (s) => `    { tag: '${s.tag}', attributes: ${JSON.stringify(s.attributes).replace(/"/g, "'")} },`,
      );
      return `  '${name}': [\n${lines.join('\n')}\n  ],`;
    })
    .join('\n');
  return `// GENERATED by scripts/generate-icons.mjs from design/icons (Lucide, ISC license,
// design/icons/LICENSE). Do not edit by hand: run \`npm run icons:generate\`.

export interface IconShape {
  tag: 'path' | 'circle' | 'rect' | 'line' | 'polyline' | 'polygon' | 'ellipse';
  attributes: Readonly<Record<string, string>>;
}

export const ICONS = {
${entries}
} as const satisfies Record<string, readonly IconShape[]>;

export type IconName = keyof typeof ICONS;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const content = await generate();
  if (process.argv.includes('--check')) {
    const current = await readFile(OUTPUT, 'utf8').catch(() => '');
    if (current !== content) {
      console.error('icons.generated.ts is out of date: run `npm run icons:generate`.');
      process.exit(1);
    }
  } else {
    await writeFile(OUTPUT, content);
  }
}
