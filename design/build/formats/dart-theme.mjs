import { DART_EXTENSION, indexByPath } from '../contract.mjs';
import { familyList, parseColor, sameValue, shadowLayers, toMs, toPx } from '../values.mjs';

export const DART_HEADER = `// GENERATED by design/ (npm run build) from design/tokens. Do not edit by hand.
//
// KdTokens is a ThemeExtension with every token for the current brightness; read it with
// KdTokens.of(context). KdConstants holds the tokens that do not change between light and
// dark, for const contexts. KdGeneratedTheme builds the light and dark ThemeData.`;

/** Dart type and lerp expression per DTCG type. */
const DART_TYPES = {
  color: { type: 'Color', lerp: (a, b) => `Color.lerp(${a}, ${b}, t)!` },
  dimension: { type: 'double', lerp: (a, b) => `lerpDouble(${a}, ${b}, t)!` },
  number: { type: 'double', lerp: (a, b) => `lerpDouble(${a}, ${b}, t)!` },
  fontWeight: { type: 'FontWeight', lerp: (a, b) => `FontWeight.lerp(${a}, ${b}, t)!` },
  fontFamily: { type: 'String?', lerp: (a, b) => `t < 0.5 ? ${a} : ${b}` },
  duration: { type: 'Duration', lerp: (a, b) => `t < 0.5 ? ${a} : ${b}` },
  cubicBezier: { type: 'Cubic', lerp: (a, b) => `t < 0.5 ? ${a} : ${b}` },
  border: { type: 'BorderSide', lerp: (a, b) => `BorderSide.lerp(${a}, ${b}, t)` },
  shadow: { type: 'List<BoxShadow>', lerp: (a, b) => `BoxShadow.lerpList(${a}, ${b}, t)!` },
  typography: { type: 'TextStyle', lerp: (a, b) => `TextStyle.lerp(${a}, ${b}, t)!` },
};

/**
 * Formats the tokens of both modes as a Dart library for Flutter.
 * @param {{ light: Array<object>, dark: Array<object> }} modes tokens named with name/camel
 */
export function formatDart({ light, dark }) {
  const lightIndex = indexByPath(light);
  const darkIndex = indexByPath(dark);
  const fields = light.map((token) => {
    const kind = DART_TYPES[token.$type];
    if (!kind) {
      throw new Error(`Token "${token.path.join('.')}": type "${token.$type}" has no Dart format`);
    }
    const darkToken = darkIndex.get(token.path.join('.')) ?? token;
    return {
      token,
      name: token.name,
      kind,
      light: dartValue(token, lightIndex),
      dark: dartValue(darkToken, darkIndex),
      constant: sameValue(token.$value, darkToken.$value),
    };
  });
  const field = (path) => {
    const found = fields.find((f) => f.token.path.join('.') === path);
    if (!found) {
      throw new Error(`The Material mapping needs the role "${path}"`);
    }
    return `t.${found.name}`;
  };

  return [
    DART_HEADER,
    '',
    "import 'dart:ui' show lerpDouble;",
    '',
    "import 'package:flutter/material.dart';",
    '',
    constantsClass(fields.filter((f) => f.constant)),
    '',
    tokensClass(fields),
    '',
    themeClass(field),
    '',
  ].join('\n');
}

function doc(token, indent) {
  return token.$description ? `${indent}/// ${token.$description}\n` : '';
}

function constantsClass(fields) {
  const body = fields
    .map((f) => {
      // A nullable constant that holds a value trips unnecessary_nullable_for_final_variable_declarations.
      const type = f.light === 'null' ? f.kind.type : f.kind.type.replace(/\?$/, '');
      return `${doc(f.token, '  ')}  static const ${type} ${f.name} = ${f.light};`;
    })
    .join('\n');
  return `/// Tokens with the same value in light and dark, usable in const expressions.
abstract final class KdConstants {
${body}
}`;
}

function tokensClass(fields) {
  const declarations = fields
    .map((f) => `${doc(f.token, '  ')}  final ${f.kind.type} ${f.name};`)
    .join('\n');
  const params = fields.map((f) => `    required this.${f.name},`).join('\n');
  const instance = (mode) =>
    fields
      .map((f) => `    ${f.name}: ${f.constant ? `KdConstants.${f.name}` : f[mode]},`)
      .join('\n');
  const copyParams = fields
    .map((f) => `    ${f.kind.type}${f.kind.type.endsWith('?') ? '' : '?'} ${f.name},`)
    .join('\n');
  const copyArgs = fields.map((f) => `      ${f.name}: ${f.name} ?? this.${f.name},`).join('\n');
  const lerpArgs = fields
    .map((f) => `      ${f.name}: ${f.kind.lerp(f.name, `other.${f.name}`)},`)
    .join('\n');

  return `/// Design tokens of Medical Kuador for one brightness.
@immutable
class KdTokens extends ThemeExtension<KdTokens> {
  const KdTokens({
${params}
  });

  /// Tokens of the light theme.
  static const KdTokens light = KdTokens(
${instance('light')}
  );

  /// Tokens of the dark theme.
  static const KdTokens dark = KdTokens(
${instance('dark')}
  );

  /// Tokens of the closest Theme. The KdGeneratedTheme themes always register them.
  static KdTokens of(BuildContext context) => Theme.of(context).extension<KdTokens>()!;

${declarations}

  @override
  KdTokens copyWith({
${copyParams}
  }) {
    return KdTokens(
${copyArgs}
    );
  }

  @override
  KdTokens lerp(covariant ThemeExtension<KdTokens>? other, double t) {
    if (other is! KdTokens) {
      return this;
    }
    return KdTokens(
${lerpArgs}
    );
  }
}`;
}

function themeClass(field) {
  const text = (path) => field(path);
  return `/// Light and dark ThemeData built only from the tokens. ThemeMode.system picks one.
abstract final class KdGeneratedTheme {
  static final ThemeData light = _build(KdTokens.light, Brightness.light);
  static final ThemeData dark = _build(KdTokens.dark, Brightness.dark);

  static ThemeData _build(KdTokens t, Brightness brightness) {
    final colorScheme = ColorScheme(
      brightness: brightness,
      primary: ${field('color.accent')},
      onPrimary: ${field('color.on-accent')},
      secondary: ${field('color.accent')},
      onSecondary: ${field('color.on-accent')},
      error: ${field('color.error')},
      onError: ${field('color.on-error')},
      surface: ${field('surface.raised')},
      onSurface: ${field('text.default')},
      onSurfaceVariant: ${field('text.muted')},
      surfaceContainerLowest: ${field('surface.sunken')},
      surfaceContainerLow: ${field('surface.base')},
      surfaceContainer: ${field('surface.raised')},
      surfaceContainerHigh: ${field('surface.overlay')},
      surfaceContainerHighest: ${field('surface.overlay')},
      outline: ${field('border.strong')}.color,
      outlineVariant: ${field('border.hairline')}.color,
    );
    final textTheme = TextTheme(
      headlineMedium: ${text('type.display')},
      titleLarge: ${text('type.title')},
      titleMedium: ${text('type.subtitle')},
      bodyLarge: ${text('type.body')},
      bodyMedium: ${text('type.body')},
      bodySmall: ${text('type.body-sm')},
      labelLarge: ${text('type.label')},
      labelMedium: ${text('type.label')},
      labelSmall: ${text('type.caption')},
    ).apply(bodyColor: ${field('text.default')}, displayColor: ${field('text.default')});

    return ThemeData(
      useMaterial3: true,
      brightness: brightness,
      colorScheme: colorScheme,
      scaffoldBackgroundColor: ${field('surface.base')},
      canvasColor: ${field('surface.base')},
      focusColor: ${field('color.focus')},
      dividerTheme: DividerThemeData(
        color: ${field('border.hairline')}.color,
        thickness: ${field('border.hairline')}.width,
      ),
      textTheme: textTheme,
      materialTapTargetSize: MaterialTapTargetSize.padded,
      extensions: <ThemeExtension<dynamic>>[t],
    );
  }
}`;
}

/** Dart literal of a resolved token. */
export function dartValue(token, index) {
  const value = token.$value;
  switch (token.$type) {
    case 'color':
      return color(value);
    case 'dimension':
      return double(toPx(value));
    case 'number':
      return double(Number(value));
    case 'fontWeight':
      return fontWeight(value);
    case 'fontFamily':
      return fontFamily(token);
    case 'duration':
      return `Duration(milliseconds: ${Math.round(toMs(value))})`;
    case 'cubicBezier':
      return `Cubic(${value.map((n) => double(n)).join(', ')})`;
    case 'border':
      return `BorderSide(color: ${color(value.color)}, width: ${double(toPx(value.width))})`;
    case 'shadow':
      return `<BoxShadow>[${shadowLayers(value)
        .map(
          (s) =>
            `BoxShadow(color: ${color(s.color)}, offset: Offset(${double(toPx(s.offsetX))}, ${double(toPx(s.offsetY))}), blurRadius: ${double(toPx(s.blur))}, spreadRadius: ${double(toPx(s.spread ?? '0px'))})`,
        )
        .join(', ')}]`;
    case 'typography': {
      const family = typographyFamily(token, index);
      return `TextStyle(${family === 'null' ? '' : `fontFamily: ${family}, `}fontSize: ${double(toPx(value.fontSize))}, fontWeight: ${fontWeight(value.fontWeight)}, height: ${double(Number(value.lineHeight))})`;
    }
    default:
      throw new Error(`Token "${token.path.join('.')}": type "${token.$type}" has no Dart format`);
  }
}

/**
 * Flutter cannot read a CSS font stack. A family token may say which family Dart uses in
 * $extensions["com.kuador.dart"].fontFamily (null = platform default); otherwise the first
 * name of the list is used.
 */
function fontFamily(token) {
  const hint = token.original?.$extensions?.[DART_EXTENSION];
  const family = hint && 'fontFamily' in hint ? hint.fontFamily : familyList(token.$value)[0];
  return family === null ? 'null' : `'${String(family).replaceAll("'", "\\'")}'`;
}

function typographyFamily(token, index) {
  const original = token.original?.$value?.fontFamily;
  const reference = typeof original === 'string' && /^\{(.+)\}$/.exec(original);
  if (reference) {
    const familyToken = index.get(reference[1]);
    if (familyToken) {
      return fontFamily(familyToken);
    }
  }
  return fontFamily({ $value: token.$value.fontFamily });
}

function color(raw) {
  const { r, g, b, a } = parseColor(raw);
  const argb = [Math.round(a * 255), r, g, b]
    .map((n) => n.toString(16).padStart(2, '0'))
    .join('')
    .toUpperCase();
  return `Color(0x${argb})`;
}

function fontWeight(raw) {
  const weight = Math.min(900, Math.max(100, Math.round(Number(raw) / 100) * 100));
  return `FontWeight.w${weight}`;
}

function double(n) {
  const rounded = Number(Number(n).toFixed(4));
  return Number.isInteger(rounded) ? `${rounded}.0` : String(rounded);
}
